// Template Literals: Template literals are a powerful feature in JavaScript that allow you to create strings with embedded expressions.
// They are enclosed by backticks (`) and can contain placeholders for variables and expressions, which are denoted by ${}. 
// This makes it easier to create complex strings without the need for concatenation.



// old way 
let name = "Yuvraj";

console.log("Hello " + name);

// new way using template literals
let name = "Yuvraj";

console.log(`Hello ${name}`);